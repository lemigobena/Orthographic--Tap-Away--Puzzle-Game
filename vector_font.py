def draw_char(char, x, y, scale):
    if char not in FONT:
        return
    glBegin(GL_LINES)
    for seg in FONT[char]:
        glVertex2f(x + seg[0][0] * scale, y - seg[0][1] * scale)
        glVertex2f(x + seg[1][0] * scale, y - seg[1][1] * scale)
    glEnd()

def draw_text(text, x, y, scale=1.0, spacing=1.2):
    curr_x = x
    for c in text:
        c = c.upper()
        draw_char(c, curr_x, y, scale)
        curr_x += spacing * scale
